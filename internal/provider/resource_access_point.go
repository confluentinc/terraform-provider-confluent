func accessPointImport(ctx context.Context, d *schema.ResourceData, meta interface{}) ([]*schema.ResourceData, error) {
	tflog.Debug(ctx, fmt.Sprintf("Importing access point %q", d.Id()), map[string]interface{}{accessPointLoggingKey: d.Id()})

	envIDAndResourceId := d.Id()
	parts := strings.Split(envIDAndResourceId, "/")
	if len(parts) != 2 {
		return nil, fmt.Errorf("error importing access point: invalid format: expected '<environment ID>/<access point ID>'")
	}
	environmentId := parts[0]
	resourceId := parts[1]
	d.SetId(resourceId)
	if err := d.Set(paramEnvironment, []interface{}{map[string]interface{}{
		paramId: environmentId,
	}}); err != nil {
		return nil, err
	}

	// Mark resource as new to avoid d.Set("") when getting 404
	d.MarkNewResource()
	if _, err := readAccessPointAndSetAttributes(ctx, d, meta); err != nil {
		return nil, fmt.Errorf("error importing access point %q: %s", d.Id(), err)
	}
	tflog.Debug(ctx, fmt.Sprintf("Finished importing access point %q", d.Id()), map[string]interface{}{accessPointLoggingKey: d.Id()})
	return []*schema.ResourceData{d}, nil
}
